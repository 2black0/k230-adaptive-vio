#!/usr/bin/env python3
"""Generate the paper's Table 4 (tab_accuracy.tex), Table 5 (tab_resource.tex)
and the ablation table (tab_ablation.tex) from the archived K230 results.

Rendering replicates paper-adaptive-floor-vio/scripts/make_accuracy_table.py
and make_ablation_table.py; all numeric values are derived from
k230-adaptive-vio/results/ through paper_metrics.py (with documented
transcribed cells for columns no archived artifact reproduces; see
paper_metrics docstring). Outputs to scripts/paper/out/ (git-ignored).

Optional: --check COMPARE.tex ... verifies byte-identical output against the
published tables (e.g. /home/ardyseto/Downloads/k230-vio/
paper-adaptive-floor-vio/tab_accuracy.tex).
"""
import argparse
import shutil
import statistics as st
from pathlib import Path

import paper_metrics as pm

PAPER = Path(__file__).resolve().parent
OUT = PAPER / "paper" / "out"

METHODS = pm.METHODS
DISPLAY = {"EqVIO": "Default EqVIO", "Ours": "SC-FBC"}
METRICS = ["ate", "rpe", "poses", "pipe", "cpu", "rss"]
LOWER_BETTER = {"ate": True, "rpe": True, "poses": False,
                "pipe": True, "cpu": True, "rss": True}
SUBHEAD = {"ate": "ATE", "rpe": "RPE", "poses": "Poses/s",
           "pipe": "P95", "cpu": "CPU", "rss": "RSS"}


def fmt(metric, v):
    if v is None:
        return "--"
    if metric in ("ate", "rpe"):
        if abs(v) >= 100:
            return f"{v:.0f}"
        if abs(v) >= 10:
            return f"{v:.1f}"
        return f"{v:.3f}"
    if metric in ("poses", "pipe"):
        return f"{v:.2f}"
    return f"{v:.1f}"  # cpu, rss


def mark(text, rank):
    if rank == 0:
        return f"\\textbf{{{text}}}"
    if rank == 1:
        return f"\\underline{{{text}}}"
    return text


def rank_map(values, keys):
    """Map each present value to a rank (0 best, 1 second) per metric."""
    out = {}
    for metric in keys:
        present = [(m, values[m][METRICS.index(metric)]) for m in METHODS
                   if values[m][METRICS.index(metric)] is not None]
        ordered = sorted(present, key=lambda kv: kv[1],
                         reverse=not LOWER_BETTER[metric])
        ranks, prev, r = {}, None, -1
        for m, val in ordered:
            if val != prev:
                r += 1
                prev = val
            ranks[m] = r
        out[metric] = ranks
    return out


def data_row(label, values, keys):
    ranks = rank_map(values, keys)
    cells = [label]
    for m in METHODS:
        for metric in keys:
            v = values[m][METRICS.index(metric)]
            cells.append(mark(fmt(metric, v), ranks[metric].get(m, 99)))
    return " & ".join(cells) + " \\\\"


def means(tables, methods, seqs):
    out = {}
    for m in methods:
        acc = []
        for mi in range(len(METRICS)):
            vals = [tables[seq][m][mi] for seq in seqs]
            vals = [v for v in vals if v is not None]
            acc.append(sum(vals) / len(vals) if vals else None)
        out[m] = tuple(acc)
    return out


def block(rows, seqs, keys):
    lines = []
    for seq in seqs:
        values = {m: rows[seq][m] for m in METHODS}
        label = pm.ROOM_KEY.get(seq, seq)
        lines.append(data_row(label, values, keys))
    transposed = {seq: {m: rows[seq][m] for m in METHODS} for seq in seqs}
    lines.append("\\midrule")
    lines.append(data_row("\\textit{Mean}", means(transposed, METHODS, seqs), keys))
    return lines


def write_accuracy_table(tables):
    """Table 4: per-sequence ATE, RPE, and P95 latency."""
    keys = ["ate", "rpe", "pipe"]
    ncol = 1 + len(keys) * len(METHODS)
    gcols = "".join("r" for _ in keys)
    colspec = "l" + ("|" + gcols) * len(METHODS)
    top = " & " + " & ".join(
        f"\\multicolumn{{{len(keys)}}}{{c}}{{{DISPLAY.get(m, m)}}}" for m in METHODS)
    subs = ["Seq."] + [SUBHEAD[k] for k in keys] * len(METHODS)
    lines = ["% Generated by scripts/make_accuracy_table.py -- do not edit by hand.",
             "\\begin{table*}[t]",
             "\\caption{Per-sequence K230 ATE and 1-s RPE (m) and per-frame processing P95 "
             "(ms; lower is better). Default EqVIO and SC-FBC use 20\\,Hz paced replay. External ATE/RPE and "
             "LEVIO/LARVIO/OpenVINS P95 use offline replay. Best and second-best "
             "available values per row and "
             "metric are in \\textbf{bold} and \\underline{underlined}.}",
             "\\label{tab:accuracy}",
             "\\centering",
             "\\small",
             "\\setlength{\\tabcolsep}{3pt}",
             f"\\begin{{tabular}}{{{colspec}}}",
             "\\toprule",
             top + " \\\\",
             " & ".join(subs) + " \\\\",
             "\\midrule",
             f"\\multicolumn{{{ncol}}}{{l}}{{\\textit{{EuRoC-MAV, 11 sequences}}}} \\\\"]
    lines += block({seq: {m: tables["EuRoC-MAV"][m][seq] for m in METHODS}
                    for seq in pm.EUROC_SEQS}, pm.EUROC_SEQS, keys)
    lines.append("\\midrule")
    lines.append(f"\\multicolumn{{{ncol}}}{{l}}{{\\textit{{TUM-VI, 6 room sequences}}}} \\\\")
    lines += block({seq: {m: tables["TUM-VI"][m][seq] for m in METHODS}
                    for seq in pm.TUMVI_SEQS}, pm.TUMVI_SEQS, keys)
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table*}"]
    path = OUT / "tab_accuracy.tex"
    path.write_text("\n".join(lines) + "\n")
    print(f"wrote {path}")


def write_resource_table(tables):
    """Table 5: per-method mean throughput and resource cost per dataset."""
    keys = ["poses", "cpu", "rss"]
    header = ["Method", "Poses/s", "CPU (\\%)", "RSS (MiB)"]
    lines = ["% Generated by scripts/make_accuracy_table.py -- do not edit by hand.",
             "\\begin{table}[t]",
             "\\caption{Mean Throughput and Resource Cost on the K230 Board. "
             "Poses/s is higher is better; CPU and RSS are lower is better. The best "
             "value per dataset and metric is in \\textbf{bold} and the second best "
             "is \\underline{underlined}. For Default EqVIO and SC-FBC, throughput is governed by the "
             "streaming rate (20 Hz) under real-time streaming replay, where feature budgeting "
             "directly reduces CPU occupancy; external methods reflect unthrottled offline "
             "execution.}",
             "\\label{tab:resource}",
             "\\centering",
             "\\small",
             f"\\begin{{tabular}}{{l{'r' * len(keys)}}}",
             "\\toprule",
             " & ".join(header) + " \\\\"]
    for name, dataset, seqs in [("EuRoC-MAV, 11 sequences", "EuRoC-MAV", pm.EUROC_SEQS),
                                ("TUM-VI, 6 room sequences", "TUM-VI", pm.TUMVI_SEQS)]:
        rows = {seq: {m: tables[dataset][m][seq] for m in METHODS} for seq in seqs}
        mrow = means(rows, METHODS, seqs)
        ranks = rank_map({m: mrow[m] for m in METHODS}, keys)
        lines.append("\\midrule")
        lines.append(f"\\multicolumn{{{1 + len(keys)}}}{{l}}{{\\textit{{{name}}}}} \\\\")
        for m in METHODS:
            cells = [DISPLAY.get(m, m)]
            for metric in keys:
                v = mrow[m][METRICS.index(metric)]
                cells.append(mark(fmt(metric, v), ranks[metric].get(m, 99)))
            lines.append(" & ".join(cells) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    path = OUT / "tab_resource.tex"
    path.write_text("\n".join(lines) + "\n")
    print(f"wrote {path}")


# --- ablation table --------------------------------------------------------

METRIC_ROWS = [
    ("features", "Mean features", None, lambda v: f"{v:.1f}" if v is not None else "--"),
    ("ate_mean", "Mean ATE (m)", True, lambda v: f"{v:.3f}" if v is not None else "--"),
    ("ate_median", "Median ATE (m)", True, lambda v: f"{v:.3f}" if v is not None else "--"),
    ("p95", "P95 Latency (ms)", True, lambda v: f"{v:.1f}" if v is not None else "--"),
    ("miss", "Exceedance (\\%)", True, lambda v: f"{v:.2f}" if v is not None else "--"),
]


def ablation_ranks(values, lower_better):
    valid = {k: v for k, v in values.items() if v is not None}
    present = sorted(valid.items(), key=lambda kv: kv[1], reverse=not lower_better)
    out, prev, r = {}, None, -1
    for label, v in present:
        if v != prev:
            r += 1
            prev = v
        out[label] = r
    return out


def ablation_dataset_rows(name, agg, dataset):
    labels = [c[0] for c in pm.ABLATION_CONFIGS]
    lines = [f"\\multicolumn{{{1 + len(labels)}}}{{l}}{{\\textit{{{name}}}}} \\\\"]
    for key, row_label, lower, fmt_fn in METRIC_ROWS:
        marks = pm.OVERRIDES_ABLATION_MARKS.get((dataset, key), {})
        cells = [row_label]
        vals = {label: agg[label][key] for label in labels}
        non_none = [v for v in vals.values() if v is not None]
        if lower is None or len(non_none) < 2 or len(set(round(v, 6) for v in non_none)) == 1:
            cells += [fmt_fn(vals[lab]) for lab in labels]
        else:
            rk = ablation_ranks(vals, lower)
            for lab in labels:
                if vals[lab] is None:
                    cells.append("--")
                    continue
                rank = marks.get(lab, rk.get(lab, 99))
                cells.append(mark(fmt_fn(vals[lab]), rank) if rank in (0, 1)
                             else fmt_fn(vals[lab]))
        lines.append(" & ".join(cells) + " \\\\")
    return lines


def write_ablation_table(agg):
    labels = [c[0] for c in pm.ABLATION_CONFIGS]
    header = ["Metric"]
    header += [r"\shortstack{Default\\EqVIO}" if label == "Default EqVIO"
               else r"\shortstack{Fixed-\\Threshold}" if label == "Fixed-Threshold"
               else label for label in labels]
    lines = ["% Updated from results/k230-paced-table6-followup/ (five-arm real-time replay).",
             "\\begin{table}[t]",
             "\\caption{Five EqVIO feature-budget policies on the K230 under 20\\,Hz paced replay. "
             "Mean features is the number of observations accepted per image; ATE and P95 "
             "are aggregated across sequences, and Exceedance is the percentage of frames "
             "with pipeline execution time $T_k>50$\\,ms. Best and second-best values per "
             "dataset are in \\textbf{bold} and \\underline{underlined}.}",
             "\\label{tab:ablation}",
             "\\centering",
             "\\footnotesize",
             "\\setlength{\\tabcolsep}{2pt}",
             f"\\begin{{tabular}}{{l{'r' * len(labels)}}}",
             "\\toprule",
             " & ".join(header) + " \\\\"]
    for name, dataset in (("EuRoC-MAV (11 sequences)", "EuRoC-MAV"),
                          ("TUM-VI (6 room sequences)", "TUM-VI")):
        lines.append("\\midrule")
        lines += ablation_dataset_rows(name, agg[dataset], dataset)
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    path = OUT / "tab_ablation.tex"
    path.write_text("\n".join(lines) + "\n")
    print(f"wrote {path}")


def check(paths):
    """Byte-compare generated tables against previously published copies."""
    names = {p.stem: p for p in paths}
    report = {}
    for name, expected in (("tab_accuracy", "tab_accuracy.tex"),
                           ("tab_resource", "tab_resource.tex"),
                           ("tab_ablation", "tab_ablation.tex")):
        target = names.get(Path(expected).stem)
        if target is None:
            continue
        generated = (OUT / expected).read_text()
        published = target.read_text()
        report[expected] = generated == published
        print(f"{expected}: {'IDENTICAL' if report[expected] else 'DIFFERS'}"
              f" vs {target}")
    return report


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", nargs="*", metavar="TEX",
                        help="byte-compare against published .tex files")
    args = parser.parse_args()
    OUT.mkdir(parents=True, exist_ok=True)
    tables = pm.accuracy_table()
    write_accuracy_table(tables)
    write_resource_table(tables)
    write_ablation_table(pm.ablation_aggregates())
    if args.check:
        check([Path(p) for p in args.check])


if __name__ == "__main__":
    main()